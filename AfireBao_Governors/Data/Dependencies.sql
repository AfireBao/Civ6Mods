-- Amani's Affluence uses one visibility requirement set for every strategic resource.
INSERT OR IGNORE INTO RequirementSets (RequirementSetId, RequirementSetType)
    SELECT 'BBG_PLAYER_CAN_SEE_' || ResourceType || '_REQSET', 'REQUIREMENTSET_TEST_ALL'
    FROM Resources
    WHERE ResourceClassType = 'RESOURCECLASS_STRATEGIC';

INSERT OR IGNORE INTO Requirements (RequirementId, RequirementType)
    SELECT 'BBG_PLAYER_CAN_SEE_' || ResourceType || '_REQUIREMENT',
           'REQUIREMENT_PLAYER_HAS_RESOURCE_VISIBILITY'
    FROM Resources
    WHERE ResourceClassType = 'RESOURCECLASS_STRATEGIC';

INSERT OR IGNORE INTO RequirementArguments (RequirementId, Name, Value)
    SELECT 'BBG_PLAYER_CAN_SEE_' || ResourceType || '_REQUIREMENT', 'ResourceType', ResourceType
    FROM Resources
    WHERE ResourceClassType = 'RESOURCECLASS_STRATEGIC';

